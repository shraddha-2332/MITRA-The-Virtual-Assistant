import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { createServer as createViteServer } from 'vite';
import { config } from '../../backend/src/config.js';
import { createSeedData } from '../../backend/src/seed.js';
import { resetDbForTests, getDb } from '../../backend/src/store.js';
import { createServer, resetRuntimeStateForTests } from '../../backend/src/server.js';
import { numericTokens } from '../../backend/src/language.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'mitra-language-browser-'));
function removeTemporaryDatabase() {
  if (path.dirname(temporary) !== path.resolve(os.tmpdir()) || !path.basename(temporary).startsWith('mitra-language-browser-')) throw new Error('Unsafe cleanup path');
  fs.rmSync(temporary, { recursive: true, force: true });
}
config.databaseFile = path.join(temporary, 'test.sqlite');
config.geminiApiKey = '';
resetDbForTests(createSeedData());
const api = createServer();
let vite;
let browser;
const packet = { generatedAt: new Date().toISOString(), reviewStatus: 'speaker-review-pending', cases: [] };
try {
  await new Promise(resolve => api.listen(0, '127.0.0.1', resolve));
  const target = `http://127.0.0.1:${api.address().port}`;
  vite = await createViteServer({ root, server: { port: 0, host: '127.0.0.1', proxy: { '/api': target } } });
  await vite.listen();
  browser = await chromium.launch({ channel: process.env.MITRA_BROWSER_CHANNEL || 'chrome', headless: true });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${vite.httpServer.address().port}`);
  if (!await page.locator('.publicComposer').isVisible()) await page.getByRole('button', { name: 'Open MIT Barshi admission assistant' }).click();
  assert.equal(await page.locator('.publicComposer button').isDisabled(), true);
  assert.equal(await page.getByRole('button', { name: 'Maintainer sign in' }).count(), 0);
  assert.equal(await page.locator('.publicAssistantPanel > footer').innerText(), 'Powered by MITCORER ©');
  assert.equal(await page.locator('.publicLanguageSelector').count(), 0);
  const languageControl = page.getByRole('combobox', { name: 'Response language', exact: true });
  await languageControl.focus();
  await languageControl.press('ArrowDown');
  await languageControl.press('Tab');
  assert.equal(await languageControl.inputValue(), 'en');
  assert.equal(await page.getByRole('button', { name: 'New conversation', exact: true }).evaluate(element => element === document.activeElement), true);
  await page.keyboard.press('Tab');
  assert.equal(await page.getByRole('button', { name: 'Minimize assistant' }).evaluate(element => element === document.activeElement), true);
  await languageControl.selectOption('auto');
  await page.getByRole('button', { name: 'Minimize assistant' }).evaluate(element => element.blur());
  fs.mkdirSync(path.join(root, 'tmp'), { recursive: true });
  await page.locator('.publicAssistantPanel').screenshot({ path: path.join(root, 'tmp/compact-language-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.publicAssistantPanel').screenshot({ path: path.join(root, 'tmp/compact-language-mobile.png') });
  await page.setViewportSize({ width: 320, height: 720 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const iconBounds = await page.locator('.publicLanguageControl').boundingBox();
  assert.ok(iconBounds.width <= 36 && iconBounds.height <= 36);
  await page.setViewportSize({ width: 1280, height: 720 });
  const questions = ['What are the first-year B.Tech fees?', 'What are hostel and mess fees?', 'What is the current CSE intake?', 'What is its intake?', 'Tell me about the library.', 'Tell me about MITCORER.', 'What are fees and hostel fees?'];
  for (const language of ['mr', 'hi']) {
    await languageControl.selectOption(language);
    for (const question of questions) {
      resetRuntimeStateForTests();
      const english = await fetch(`${target}/api/public-assistant/ask`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ question, language: 'en' }) }).then(r => r.json());
      await page.locator('.publicComposer textarea').fill(question);
      const response = page.waitForResponse(r => r.url().endsWith('/api/public-assistant/ask') && r.request().method() === 'POST');
      await page.locator('.publicComposer textarea').press('Enter');
      const received = await response;
      assert.equal(received.status(), 200);
      const { data } = await received.json();
      await page.locator('.publicComposer textarea').waitFor({ state: 'visible' });
      await page.waitForFunction(() => !document.querySelector('.publicComposer textarea').disabled);
      const visible = await page.locator('.publicBubble.assistant').last().innerText();
      assert.match(visible, /[\u0900-\u097f]/);
      assert.equal(data.requestedLanguage, language);
      const factualText = data.sections?.map(section => section.answer).join('\n') || data.answer;
      for (const number of numericTokens(factualText)) assert.ok(numericTokens(visible).has(number), `UI omitted ${number}`);
      assert.equal(await page.locator('.publicEvidence').count(), 0);
      for (const record of data.evidence) {
        assert.equal(record.passage.sha256.length, 64);
        assert.ok(record.citationId.startsWith(`${record.id}:`));
      }
      if (data.localizationStatus === 'fallback') assert.ok(visible.includes(english.data.answer.split('\n')[0]));
      packet.cases.push({ question, language, english: english.data.answer, answer: data.answer, evidence: data.evidence, localizationStatus: data.localizationStatus, reviewer: '', verdict: 'pending', corrections: '' });
    }
  }
  await page.route('**/api/public-assistant/ask', route => route.abort());
  await page.locator('.publicComposer textarea').fill('What are fees?');
  await page.locator('.publicComposer textarea').press('Enter');
  await page.waitForFunction(() => !document.querySelector('.publicComposer textarea').disabled);
  assert.match(await page.locator('.publicBubble.assistant').last().innerText(), /अभी आधिकारिक जानकारी/);
  await page.unroute('**/api/public-assistant/ask');
  await languageControl.selectOption('en');
  await page.locator('.publicComposer textarea').fill('What is the current CSE intake?');
  const recovered = page.waitForResponse(r => r.url().endsWith('/api/public-assistant/ask'));
  await page.locator('.publicComposer textarea').press('Enter');
  assert.equal((await recovered).status(), 200);
  await page.waitForFunction(() => !document.querySelector('.publicComposer textarea').disabled);
  assert.match(await page.locator('.publicBubble.assistant').last().innerText(), /120/);
  await page.locator('.publicComposer textarea').fill('Which B.Tech programmes are available at MITCORER?');
  const programmesResponse = page.waitForResponse(r => r.url().endsWith('/api/public-assistant/ask'));
  await page.locator('.publicComposer textarea').press('Enter');
  assert.equal((await programmesResponse).status(), 200);
  await page.waitForFunction(() => !document.querySelector('.publicComposer textarea').disabled);
  const programmeBubble = page.locator('.publicBubble.assistant').last();
  assert.equal(await programmeBubble.locator('.publicAnswerList li').count(), 6);
  assert.match(await programmeBubble.innerText(), /Choice code: 0690124210/);
  assert.equal(await programmeBubble.locator('a').count() > 0, true);
  assert.equal(await page.locator('.publicEvidence').count(), 0);
  await page.screenshot({ path: path.join(root, 'tmp/answer-programmes.png') });
  await page.locator('.publicComposer textarea').fill('What is the fee structure?');
  const feeResponse = page.waitForResponse(r => r.url().endsWith('/api/public-assistant/ask'));
  await page.locator('.publicComposer textarea').press('Enter');
  const feeData = (await (await feeResponse).json()).data;
  await page.waitForFunction(() => !document.querySelector('.publicComposer textarea').disabled);
  const feeBubble = page.locator('.publicBubble.assistant').last();
  assert.equal(await feeBubble.locator('.publicAnswerList').count(), 2, feeData.answer);
  assert.equal(await feeBubble.locator('.publicAnswerList li').count(), 10);
  for (const number of numericTokens(feeData.answer)) assert.ok(numericTokens(await feeBubble.innerText()).has(number), `Missing ${number}; UI=${await feeBubble.innerText()}; API=${feeData.answer}`);
  assert.equal(await feeBubble.locator('a').count() >= 2, true);
  await page.screenshot({ path: path.join(root, 'tmp/answer-fees.png') });
  const staleLibraryUrl = 'https://www.mitcorer.edu.in/about-lib-details.html';
  await page.route('**/api/public-assistant/ask', async route => {
    const response = await route.fetch();
    const payload = await response.json();
    payload.data.sourceUrl = staleLibraryUrl;
    payload.data.officialLinks = [{ label: 'Library', url: staleLibraryUrl }];
    await route.fulfill({ response, json: payload });
  });
  await page.locator('.publicComposer textarea').fill('Tell me about the library.');
  const legacyLibraryResponse = page.waitForResponse(r => r.url().endsWith('/api/public-assistant/ask'));
  await page.locator('.publicComposer textarea').press('Enter');
  assert.equal((await legacyLibraryResponse).status(), 200);
  await page.waitForFunction(() => !document.querySelector('.publicComposer textarea').disabled);
  const legacyLibraryBubble = page.locator('.publicBubble.assistant').last();
  assert.equal(await legacyLibraryBubble.locator('a[href="https://mitcorer.edu.in/about-lib-details.php"]').count(), 1);
  assert.equal(await legacyLibraryBubble.locator(`a[href="${staleLibraryUrl}"]`).count(), 0);
  await page.unroute('**/api/public-assistant/ask');
  const literal = 'Library evidence <img src=x onerror="window.__mitraInjected=true">. Timings are unpublished.';
  getDb().knowledge.find(record => record.id === 'KB-20').text = literal;
  await page.locator('.publicComposer textarea').fill('Tell me about the library.');
  const safeResponse = page.waitForResponse(r => r.url().endsWith('/api/public-assistant/ask'));
  await page.locator('.publicComposer textarea').press('Enter');
  assert.equal((await safeResponse).status(), 200);
  await page.waitForFunction(() => !document.querySelector('.publicComposer textarea').disabled);
  const safeDetails = page.locator('.publicBubble.assistant').last().locator(':scope > div').last();
  assert.ok((await safeDetails.textContent()).includes(literal));
  assert.equal(await safeDetails.locator('img').count(), 0);
  assert.equal(await page.evaluate(() => window.__mitraInjected === true), false);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  fs.mkdirSync(path.join(root, 'tmp/language-review'), { recursive: true });
  fs.writeFileSync(path.join(root, 'tmp/language-review/review-packet.json'), `${JSON.stringify(packet, null, 2)}\n`);
  const markdown = ['# Language review packet', '', 'Status: **speaker-review-pending**. Generated from isolated seeded API responses, not the live maintained database.', '', 'For each case, check meaning against the English evidence, category/route, academic year, amounts, codes, negation, eligibility conditions, uncertainty and fluency. Mark Accept / Correct / Reject; record reviewer name, language competence, date and corrections. Native script and matching numbers alone do not establish correctness.', '', 'Fallback cases intentionally retain English: supply a complete reviewed translation of the knowledge record through Knowledge → Edit record. Do not approve a translation against a different prepared answer. Source changes require review again.', '', ...packet.cases.flatMap((item, index) => [`## Case ${index + 1}: ${item.language} — ${item.question}`, '', `Localization: ${item.localizationStatus}`, '', '### English response', '', item.english, '', '### Displayed answer', '', item.answer, '', '### Supporting evidence', '', ...(item.evidence || []).map(record => `${record.id}: ${record.text || record.title || ''}`), '', 'Reviewer / competence / date: __________', '', 'Meaning / conditions / fluency verdicts: __________', '', 'Corrections: __________', ''])].join('\n');
  fs.writeFileSync(path.join(root, 'tmp/language-review/REVIEW_PACKET.md'), `${markdown}\n`);
  console.log('PASS: restored footer, compact header language selector with keyboard/mobile checks, 14 real API language journeys, hidden evidence panel, safe literal rendering, empty-submit guard, network recovery and browser errors. Speaker approval remains pending.');
} finally {
  await browser?.close();
  await vite?.close();
  if (api.listening) await new Promise(resolve => api.close(resolve));
  resetDbForTests({});
  removeTemporaryDatabase();
}
